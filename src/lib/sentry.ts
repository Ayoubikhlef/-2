/**
 * Sentry Client SDK Initialization
 *
 * This module initializes the Sentry client for capturing errors and events.
 * Configuration is loaded from environment variables with sensible defaults.
 */

import * as Sentry from '@sentry/nextjs';

// Load Sentry DSN from environment
const dsn = process.env.SENTRY_DSN;

export const sentryInit = (isClient = true) => {
  if (!dsn && isClient) {
    // Don't initialize client-side without DSN to avoid warnings
    return;
  }

  // Configure Sentry Client
  Sentry.init({
    dsn: dsn,

    // Debug mode - enabled in development for debugging setup issues
    debug: process.env.NODE_ENV === 'development',

    // Environment tracking
    environment: process.env.NODE_ENV || 'development',

    // Release tracking (auto-generated by Vercel or build script)
    release: process.env.VERCEL_GIT_COMMIT_SHA || process.env.NPM_VERSION,

    // Sample rate - capture this percentage of traces (0 to 1)
    tracesSampleRate: process.env.SENTRY_TRACES_SAMPLE_RATE
      ? parseFloat(process.env.SENTRY_TRACES_SAMPLE_RATE)
      : 0.2, // Default: sample 20% of transactions in production

    // Profiling sample rate (requires Sentry.io profiling support)
    profilesSampleRate: process.env.NODE_ENV === 'production' ? 0.1 : 0,

    // Performance monitoring
    beforeSendTransaction: function (event) {
      // Filter out internal/irrelevant transactions
      const ignoredPaths = ['/api/*', '/_next/*'];
      if (ignoredPaths.some((path) => event.transaction.includes(path))) {
        return null;
      }
      return event;
    },

    // Scope configuration with browser integrations
    integrations: [
      new (Sentry.Integrations as any).BrowserTracing(),
      new (Sentry.Integrations as any).GlobalHandlers({
        prepend: false,
      }),
    ],

    // Trace propagation targets for distributed tracing
    tracePropagationTargets: [
      process.env.API_PUBLIC_URL || '/api',
      'localhost:3001',
      ...[process.env.NEXT_PUBLIC_TRACING_TARGETS].map((s) => s.trim()),
    ].filter(Boolean),

    // Session replay options
    replays: {
      maskAllInputs: process.env.SENTRY_MASK_ALL_INPUTS === 'true',
      maskTexts: ['password', 'token', 'secret', 'key'],
      maskAllOptions: true,
    },
  });
};

// Export the initialized client globally
if (typeof window !== 'undefined') {
  if (dsn) {
    // @ts-ignore - Next.js global is extended at build time
    (window as any).__sentry_init = sentryInit;
  }
}

export default sentryInit;
