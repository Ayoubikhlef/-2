function svgImage(label: string, color: string, ink = '#ffffff'): string {
  const text = label.trim().slice(0, 3);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="800" viewBox="0 0 800 800">
<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
<stop offset="0" stop-color="${color}"/><stop offset="1" stop-color="${color}99"/>
</linearGradient></defs>
<rect width="800" height="800" fill="url(#g)"/>
<circle cx="640" cy="160" r="220" fill="#ffffff" opacity="0.08"/>
<circle cx="120" cy="700" r="260" fill="#ffffff" opacity="0.06"/>
<text x="400" y="450" font-family="Arial,Helvetica,sans-serif" font-size="190" font-weight="800" text-anchor="middle" fill="${ink}">${text}</text>
</svg>`;
  return `data:image/svg+xml;base64,${Buffer.from(svg, 'utf8').toString('base64')}`;
}

function products(items: Array<[string, number, string, string]>, color: string): RenderProduct[] {
  return items.map(([name, price, category, description], index) => ({
    id: `demo-p${index + 1}`,
    name,
    price,
    category,
    description,
    imageUrl: svgImage(name, color),
  }));
}

function services(items: Array<[string, string]>): RenderService[] {
  return items.map(([title, description]) => ({ title, description }));
}

