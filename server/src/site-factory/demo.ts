const cache = new Map<string, RenderedSite>();

export const DEMO_SLUGS = Object.keys(DEMO);

export function isDemoTemplate(slug: string): boolean {
  return Object.prototype.hasOwnProperty.call(DEMO, slug);
}

export function buildDemoConfig(slug: string, lang: Lang): RenderConfig {
  const seed = DEMO[slug] || DEMO.landing;
  const [primary, secondary] = ACCENTS[slug] || ACCENTS.landing;
  return {
    siteId: `demo-${slug}`,
    templateSlug: isDemoTemplate(slug) ? slug : 'landing',
    siteName: seed.name,
    tagline: seed.tagline,
    description: seed.description,
    category: seed.category,
    phone: OWNER.phone,
    whatsapp: OWNER.whatsapp,
    email: OWNER.email,
    address: OWNER.address,
    city: OWNER.city,
    language: lang,
    primaryColor: primary,
    secondaryColor: secondary,
    logoUrl: null,
    coverUrl: seed.cover,
    gallery: seed.gallery,
    socials: { facebook: '', instagram: '', tiktok: '' },
    hours: seed.hours,
    services: seed.services,
    products: seed.products || [],
    team: seed.team,
    subdomain: `demo-${slug}`,
    customDomain: null,
    preview: true,
    apiBase: '',
  };
}

export function renderTemplateDemo(slug: string, lang: Lang): RenderedSite {
  const key = `${slug}:${lang}`;
  const cached = cache.get(key);
  if (cached) return cached;
  const rendered = renderSite(buildDemoConfig(slug, lang));
  if (cache.size > 72) cache.clear();
  cache.set(key, rendered);
  return rendered;
}
