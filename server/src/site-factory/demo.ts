/** [name, price, category, description, optional image override] */
type ProductSeed = [string, number, string, string, string?];

function products(group: PhotoGroup, items: ProductSeed[], start = 1): RenderProduct[] {
  return items.map(([name, price, category, description, image], index) => ({
    id: `demo-p${index + 1}`,
    name,
    price,
    category,
    description,
    imageUrl: image || photo(group, start + index, 800, 800),
  }));
}

function services(items: Array<[string, string]>): RenderService[] {
  return items.map(([title, description]) => ({ title, description }));
}

/** [name, price per day, category, description, specs, optional image index] */
type CarSeed = [string, number, string, string, RentalSpecs, number?];

function rentalCars(items: CarSeed[]): RenderProduct[] {
  return items.map(([name, price, category, description, rental, imageIndex], index) => ({
    id: `demo-car${index + 1}`,
    name,
    price,
    category,
    description,
    rental,
    imageUrl: photo('car', imageIndex || index + 1, 900, 650),
  }));
}

